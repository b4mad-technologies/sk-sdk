// Ratchet for world-author's intentional embedded manifest corpus.
// This package tests parsing, rendering, validation, and executable docs, so
// inline manifests are appropriate only at those oracle seams. Reusable world
// vehicles belong in package-owned fixtures elsewhere; authoring examples stay
// external under docs/examples and enter src only through the generated corpus.

import { readdirSync, readFileSync } from "node:fs";
import { relative, resolve } from "node:path";
import { describe, expect, it } from "vitest";

const REPO_ROOT = resolve(import.meta.dirname, "../../../..");
// Repository-only policy tooling stays outside the package build root and public API.
const { checkEmbeddedManifestClassifications } = await import(
	resolve(REPO_ROOT, "scripts/lib/embedded-manifest-classifications.ts")
);
const SRC_ROOT = resolve(import.meta.dirname, "..");
const SCHEMA_MARKER = ["#:schema", "https://spellkave.dev/schema/world-manifest-1.0.0.json"].join(
	" ",
);
const TOML_SCHEMA_VERSION = ["schema_version", "=", '"1.0.0"'].join(" ");
const OBJECT_SCHEMA_VERSION = ["schema_", "version:", ' "1.0.0"'].join("");
const signatures = [
	{ name: "toml_version", matches: (source: string) => source.includes(TOML_SCHEMA_VERSION) },
	{ name: "schema_directive", matches: (source: string) => source.includes(SCHEMA_MARKER) },
	{ name: "schema_object", matches: (source: string) => source.includes(OBJECT_SCHEMA_VERSION) },
	{
		name: "schema_shape",
		matches: (source: string) => /schema_version["']?\s*(?::|=)/.test(source),
	},
];
const categories = [
	"handwritten_toml_oracle",
	"generated_toml_corpus",
	"schema_object_oracle",
	"production_schema_constructor",
];

describe("world-author embedded manifest inventory", () => {
	it("preserves every overlapping signature and narrowly justified local classification", () => {
		const files = readdirSync(SRC_ROOT, { recursive: true })
			.map(String)
			.filter((path) => path.endsWith(".ts"))
			.map((path) => ({
				path: relative(SRC_ROOT, resolve(SRC_ROOT, path)),
				source: readFileSync(resolve(SRC_ROOT, path), "utf8"),
			}));
		expect(
			checkEmbeddedManifestClassifications(files, [
				{
					category: "world_author_inline",
					allowedCategories: categories,
					// The original inclusive 40-character minimum is a strict lower bound of 39.
					minimumRationaleLength: 39,
					matches: (source: string) => signatures.some((signature) => signature.matches(source)),
					signatures,
				},
			]),
		).toEqual([]);
		const declaredCategories = files.flatMap(({ source }) =>
			[...source.matchAll(/^\/\/ embedded-manifest: (.+)$/gm)].map(
				(match) => JSON.parse(match[1]!).category as string,
			),
		);
		expect([...new Set(declaredCategories)].sort()).toEqual([...categories].sort());
	});

	it("keeps the embedded documentation corpus generated from its external sources", () => {
		const generated = readFileSync(resolve(SRC_ROOT, "corpus.generated.ts"), "utf8");

		expect(generated).toMatch(/^\/\/ GENERATED by scripts\/generate-authoring-corpus\.ts/);
		expect(generated).toContain("Source of truth: packages/spellkave-world-author/docs/**");
	});
});
