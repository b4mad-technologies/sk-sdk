import { type AuthoringDoc, type AuthoringExample, isSupportedAuthoringDoc } from "./corpus";

// Must match this doc's own PROSE_DOCS id in `corpus.ts` ("index").
const DOCS_INDEX_ID = "index";

const ONRAMP_ID = "onramp";

/** The onramp's PROSE_DOCS id has no matching filename stem — its real file
 * is `README.md` (same special-casing `corpus.ts`'s own generator uses). */
function docFilename(doc: AuthoringDoc): string {
	if (doc.source_path) return `../../${doc.source_path.replace(/^packages\//, "")}`;
	if (doc.id === ONRAMP_ID) return "README.md";
	if (doc.id === "patterns") return "patterns/index.md";
	if (doc.kind === "repair" && doc.id !== "running-an-authored-act") {
		return `repairs/${doc.id}.md`;
	}
	return `${doc.id}.md`;
}

function docRow(doc: AuthoringDoc): string {
	return `| [\`${doc.id}\`](./${docFilename(doc)}) | ${doc.summary} |`;
}

function docSection(title: string, docs: AuthoringDoc[]): string {
	if (docs.length === 0) return "";
	const rows = docs
		.slice()
		.sort((a, b) => a.id.localeCompare(b.id))
		.map(docRow)
		.join("\n");
	return `### ${title}\n\n| Doc | Summary |\n|---|---|\n${rows}\n`;
}

export function renderAuthoringDocsIndex(
	allDocs: readonly AuthoringDoc[],
	examples: readonly AuthoringExample[],
): string {
	const docs = allDocs.filter((d) => d.id !== DOCS_INDEX_ID);
	const supported = docs.filter(isSupportedAuthoringDoc);

	const onramp = supported.filter((d) => d.id === "onramp");
	const toolReference = supported.filter((d) => d.id === "tool-reference");
	const guides = supported.filter((d) => d.kind === "guide" && d.id !== "onramp");
	const planning = docs.filter(
		(d) => d.publication && d.publication.content_status !== "implemented",
	);
	const references = supported.filter((d) => d.kind === "reference" && d.id !== "tool-reference");
	const repairs = supported.filter((d) => d.kind === "repair");
	const exampleDocs = supported
		.filter((d) => d.kind === "example")
		.slice()
		.sort((a, b) => a.id.localeCompare(b.id));

	const exampleRows = exampleDocs
		.map((doc) => {
			const example = examples.find((e) => e.id === doc.id);
			const tags = example ? example.tags.join(", ") : "";
			return `| [\`${doc.id}\`](./examples/${doc.id}.md) | ${doc.summary} | ${tags} |`;
		})
		.join("\n");

	const sections = [
		docSection("Onramp — start here", onramp),
		docSection("Guides", guides),
		docSection("Planning references — unimplemented or historical", planning),
		docSection("Reference", references),
		docSection("Troubleshooting", repairs),
		docSection("Tool reference (generated)", toolReference),
	]
		.filter((s) => s.length > 0)
		.join("\n");

	const total = docs.length + 1; // +1 for this index page itself

	return `# Authoring docs — corpus index

<!-- GENERATED by scripts/generate-authoring-docs-index.ts. Do not edit by hand. -->

Every doc in the composed public corpus, grouped by kind, with a one-line
summary from its owning metadata. World-author owns authoring prose and
patterns; CLI owns its workflow guide. This is the same corpus \`spellkave_docs\` serves to an
authoring agent — this page exists for browsing it as plain markdown (GitHub
render, no external site generator) instead of calling the tool or reading
\`corpus.ts\` source. ${total} docs, ${exampleDocs.length} of them worked
\`.toml\` examples.

New here? Start at [\`README.md\`](./README.md) (\`onramp\` — AUTHOR + PLAYER tools).
AUTHOR verb deep-dive: [\`getting-started-with-verbs.md\`](./getting-started-with-verbs.md).
Something broken? Troubleshooting repairs below, or \`sk docs --query "<symptom>"\`.

The PLAYER/DM tool surface is a separate registry in a separate package, not
part of this corpus — see
[\`../../spellkave-tool-player/docs/tool-reference.md\`](../../spellkave-tool-player/docs/tool-reference.md).

${sections}
### Worked examples (\`docs/examples/**\`)

Each example is a validated \`.toml\` fixture plus a \`.md\` walkthrough. Tags
come from the example's own sidecar metadata.

| Example | Intent | Tags |
|---|---|---|
${exampleRows}
`;
}
