import { existsSync, mkdtempSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";

import {
	currentWorktreeRoot,
	readCurrentContext,
	readLastUsedProfile,
	resolveCliPaths,
	writeCurrentContext,
	writeLastUsedProfile,
} from "../core/node-io";
import {
	isLocalNodeProfile,
	localNodeProfileName,
	scopedCurrentContextFile,
	scopedLastUsedProfileFile,
	worktreeScopeKey,
} from "../core/paths";
import { parsePersonaProfile, serializePersonaProfile } from "../core/profile";
import { readCurrentContext as readCurrentContextPure } from "../core/resolve";

const savedHome = process.env.SPELLKAVE_HOME;

function freshPaths() {
	process.env.SPELLKAVE_HOME = mkdtempSync(join(tmpdir(), "sk-context-"));
	return resolveCliPaths();
}

describe("per-worktree current context", () => {
	afterEach(() => {
		if (savedHome === undefined) delete process.env.SPELLKAVE_HOME;
		else process.env.SPELLKAVE_HOME = savedHome;
	});

	it("round-trips for the current worktree and trims", () => {
		const paths = freshPaths();
		expect(readCurrentContext(paths)).toBeUndefined();
		writeCurrentContext(paths, "  staging  ");
		expect(readCurrentContext(paths)).toBe("staging");
	});

	it("keeps two worktrees apart", () => {
		const paths = freshPaths();
		const io = {
			readFileSync: (p: string) => {
				if (p === scopedCurrentContextFile(paths, "/w/a")) return "a-ctx\n";
				if (p === scopedCurrentContextFile(paths, "/w/b")) return "b-ctx\n";
				throw Object.assign(new Error("missing"), { code: "ENOENT" });
			},
		};
		expect(readCurrentContextPure(paths, io, "/w/a")).toBe("a-ctx");
		expect(readCurrentContextPure(paths, io, "/w/b")).toBe("b-ctx");
		expect(readCurrentContextPure(paths, io, "/w/c")).toBeUndefined();
	});

	it("reads nothing and refuses to write outside a git worktree", () => {
		const paths = freshPaths();
		const outside = mkdtempSync(join(tmpdir(), "sk-no-git-"));
		expect(currentWorktreeRoot(outside)).toBeUndefined();
		expect(readCurrentContext(paths, outside)).toBeUndefined();
		expect(() => writeCurrentContext(paths, "staging", outside)).toThrow(
			/not inside a git worktree/,
		);
	});

	it("is independent of the last-used pointer in both directions", () => {
		const paths = freshPaths();
		const root = currentWorktreeRoot() as string;
		writeLastUsedProfile(paths, "kira");
		expect(existsSync(scopedCurrentContextFile(paths, root))).toBe(false);
		expect(readCurrentContext(paths)).toBeUndefined();

		writeCurrentContext(paths, "staging");
		expect(readLastUsedProfile(paths)).toBe("kira");
		expect(readFileSync(scopedLastUsedProfileFile(paths, root), "utf8").trim()).toBe("kira");
	});

	it("rejects a context name that could escape the profiles directory", () => {
		const paths = freshPaths();
		expect(() => writeCurrentContext(paths, "../x")).toThrow();
	});
});

describe("local node profile name", () => {
	it("is local-<dir>-<first 6 hex of the worktree hash>", () => {
		const root = "/Users/me/src/spellkave/author-ux";
		expect(localNodeProfileName(root)).toBe(
			`local-author-ux-${worktreeScopeKey(root).slice(0, 6)}`,
		);
	});

	it("differs for two clones with the same directory name", () => {
		expect(localNodeProfileName("/a/author-ux")).not.toBe(localNodeProfileName("/b/author-ux"));
	});

	it("recognises only the pattern plus a loopback URL", () => {
		const name = localNodeProfileName("/a/author-ux");
		expect(isLocalNodeProfile(name, "http://127.0.0.1:7649")).toBe(true);
		expect(isLocalNodeProfile(name, "http://localhost:7649")).toBe(true);
		expect(isLocalNodeProfile(name, "http://[::1]:7649")).toBe(true);
		expect(isLocalNodeProfile(name, "https://world.example.test")).toBe(false);
		expect(isLocalNodeProfile("local-prod", "http://127.0.0.1:7649")).toBe(false);
		expect(isLocalNodeProfile("staging", "http://127.0.0.1:7649")).toBe(false);
	});
});

describe("serializePersonaProfile", () => {
	it("round-trips through the parser and keeps the header", () => {
		const profile = {
			connection: { url: "http://127.0.0.1:7649", db: "spellkave-dev" },
			identity: { role: "author", in_world_self: "0" },
			defaults: {},
		};
		const text = serializePersonaProfile(profile, ["Generated by `sk dev up`."]);
		expect(text.startsWith("# Generated by `sk dev up`.\n")).toBe(true);
		expect(parsePersonaProfile(text)).toEqual(profile);
	});
});
