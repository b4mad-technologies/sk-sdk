/**
 * Writes `src/core/kernel_contract.generated.ts`: the part of the world
 * kernel schema snapshot this SDK uses (STRICT_TABLES, STRICT_REDUCERS and the
 * named types they reach) plus the contract epoch (sk-jay0.7.389.3). The SDK
 * ships this compact form to every client, browser included, instead of the
 * whole snapshot; connect() compares it with the served module definition.
 *
 * Usage: tsx packages/spellkave-sdk/scripts/generate-kernel-contract.ts [--check]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { restrictSnapshot, type SchemaSnapshot } from "../src/core/world-contract/index.ts";
import { STRICT_REDUCERS } from "../src/core/world-contract/strict-reducers.ts";
import { STRICT_TABLES } from "../src/reader-manifest.ts";

const SDK = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const OUTPUT = join(SDK, "src/core/kernel_contract.generated.ts");

export function render(): string {
	const snapshot = JSON.parse(
		readFileSync(new URL(import.meta.resolve("@spellkave/bindings/world.schema.json")), "utf8"),
	) as SchemaSnapshot & {
		$comment?: string;
	};
	const epoch = (
		JSON.parse(readFileSync(new URL(import.meta.resolve("@spellkave/bindings/epoch.json")), "utf8")) as { world?: unknown }
	).world;
	if (typeof epoch !== "number")
		throw new Error("generate-kernel-contract: @spellkave/bindings/epoch.json has no world epoch");
	const used = restrictSnapshot(snapshot, {
		tables: [...STRICT_TABLES],
		reducers: [...STRICT_REDUCERS],
	});
	const missing = [...STRICT_TABLES].filter((t) => !(t in used.tables) && !(t in used.views));
	missing.push(...STRICT_REDUCERS.filter((r) => !(r in used.reducers)));
	if (missing.length > 0) {
		throw new Error(
			`generate-kernel-contract: strict items absent from the world snapshot: ${missing.join(", ")}`,
		);
	}
	return [
		"// GENERATED by packages/spellkave-sdk/scripts/generate-kernel-contract.ts from",
		"// @spellkave/bindings/{world.schema.json,epoch.json}. Do not edit:",
		"// regenerate with `pnpm --filter @spellkave/sdk run generate:kernel-contract`.",
		'import type { SchemaSnapshot } from "./world-contract/index.ts";',
		"",
		"/** The world contract epoch this client was built for. */",
		`export const KERNEL_CONTRACT_EPOCH = ${epoch};`,
		"",
		"/** The world schema items this SDK uses, as built. */",
		`export const KERNEL_CONTRACT: SchemaSnapshot = ${JSON.stringify(used)};`,
		"",
	].join("\n");
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
	const next = render();
	if (process.argv.includes("--check")) {
		let current = "";
		try {
			current = readFileSync(OUTPUT, "utf8");
		} catch {}
		if (current !== next) {
			console.error(
				`[FAIL] ${OUTPUT} is stale; run pnpm --filter @spellkave/sdk run generate:kernel-contract`,
			);
			process.exitCode = 1;
		}
	} else {
		writeFileSync(OUTPUT, next);
		console.log(`[generate-kernel-contract] wrote ${OUTPUT}`);
	}
}
