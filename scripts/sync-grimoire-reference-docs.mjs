// Syncs the DSL grammar and the manifest format reference from sk-grimoire.
//
// sk-grimoire defines the language and generates both pages from its crates
// (`cargo run --locked -p spellkave-reference-docs -- --write`, with its own
// drift check). sk-sdk does not generate them. This script copies the two
// pages from one pinned sk-grimoire commit into the world-author docs and
// replaces the generator banner with a banner that names this script and the
// pin, so a reader of the copy knows where the page comes from.
//
// Write:  node scripts/sync-grimoire-reference-docs.mjs
// Check:  node scripts/sync-grimoire-reference-docs.mjs --check
//
// `--check` fetches the pinned pages again and fails when a committed page
// differs (a hand edit, or a pin bump without a sync run). CI runs it in
// `.github/workflows/grimoire-reference-sync.yml`.
//
// To take a newer reference: set GRIMOIRE_COMMIT to the full commit id of the
// wanted sk-grimoire commit, run the write mode, and commit the pin together
// with the two pages.
//
// The source is the public sk-grimoire repository at an immutable commit id.
// `--source <dir>` reads `<dir>/docs/<page>` from a local checkout instead of
// the network; that checkout must be at GRIMOIRE_COMMIT for the result to be
// correct, and the script does not verify this.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const GRIMOIRE_REPOSITORY = "b4mad-technologies/sk-grimoire";
const GRIMOIRE_COMMIT = "7c157a7978b1a568e03e5470285259390dee5574";
const PAGES = ["dsl-grammar.md", "manifest-format.md"];

const SCRIPT_PATH = "scripts/sync-grimoire-reference-docs.mjs";
const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const targetDir = path.join(repoRoot, "packages/spellkave-world-author/docs");

// The banner sk-grimoire's generator writes: one HTML comment line that
// starts with "Generated by". Exactly one such line must exist, so a changed
// upstream layout fails the sync instead of producing a page without banner.
const UPSTREAM_BANNER = /^<!-- Generated by .* -->$/;

function banner(page) {
	return `<!-- Synced by ${SCRIPT_PATH} from ${GRIMOIRE_REPOSITORY} docs/${page} at commit ${GRIMOIRE_COMMIT}. Do not edit by hand. -->`;
}

function render(page, upstream) {
	const lines = upstream.replaceAll("\r\n", "\n").split("\n");
	const hits = lines.flatMap((line, index) => (UPSTREAM_BANNER.test(line) ? [index] : []));
	if (hits.length !== 1) {
		throw new Error(
			`${page}: expected exactly one sk-grimoire generator banner, found ${hits.length}`,
		);
	}
	lines[hits[0]] = banner(page);
	return lines.join("\n");
}

async function fetchUpstream(page, sourceDir) {
	if (sourceDir) return readFile(path.join(sourceDir, "docs", page), "utf8");
	const url = `https://raw.githubusercontent.com/${GRIMOIRE_REPOSITORY}/${GRIMOIRE_COMMIT}/docs/${page}`;
	const response = await fetch(url);
	if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
	return response.text();
}

function parseArgs(argv) {
	const options = { check: false, sourceDir: undefined };
	for (let i = 0; i < argv.length; i += 1) {
		const arg = argv[i];
		if (arg === "--check") options.check = true;
		else if (arg === "--source" && argv[i + 1]) options.sourceDir = path.resolve(argv[++i]);
		else throw new Error(`unknown or incomplete argument: ${arg}`);
	}
	return options;
}

async function main() {
	const { check, sourceDir } = parseArgs(process.argv.slice(2));
	const drifted = [];
	for (const page of PAGES) {
		const expected = render(page, await fetchUpstream(page, sourceDir));
		const target = path.join(targetDir, page);
		const relative = path.relative(repoRoot, target);
		const current = await readFile(target, "utf8").catch(() => undefined);
		if (current === expected) continue;
		if (check) drifted.push(relative);
		else {
			await writeFile(target, expected);
			console.log(`wrote ${relative}`);
		}
	}
	if (drifted.length > 0) {
		console.error(
			`Out of sync with ${GRIMOIRE_REPOSITORY}@${GRIMOIRE_COMMIT}:\n` +
				drifted.map((file) => `  ${file}\n`).join("") +
				`Run: node ${SCRIPT_PATH}`,
		);
		process.exitCode = 1;
	} else if (check) {
		console.log(`in sync with ${GRIMOIRE_REPOSITORY}@${GRIMOIRE_COMMIT}`);
	}
}

await main();
